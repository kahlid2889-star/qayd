const slice = (a, b) => src.slice(a, b).join("\n");
const bal0 = at("const Baloot = (() => {"), bal1 = at("module.exports = Baloot;");
const bots0 = at("const QaidBots = (() => {"), bots1 = at("function botAt(player) {", bots0);
